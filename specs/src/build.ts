// ------------------------------------------------------------------ write / check

export function outputs(): Record<string, string> {
  const yaml = (doc: Schema) => `# ${GENERATED_NOTE}\n` + YAML.stringify(doc, { lineWidth: 0, aliasDuplicateObjects: false });
  const json = (doc: Schema) => JSON.stringify(doc, null, 2) + '\n';
  const files: Record<string, string> = {
    'openapi/ocpp-csms-gateway.openapi.yaml': yaml(gatewaySpec()),
    'openapi/ocpp-messages.openapi.yaml': yaml(messagesSpec()),
  };
  for (const v of versionKeys) files[`json-schema/${v}-inbound-frame.schema.json`] = json(inboundFrameSchema(v));
  return files;
}

async function main() {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, content] of Object.entries(outputs())) {
    const file = path.join(ROOT, rel);
    if (check) {
      const current = await readFile(file, 'utf8').catch(() => '');
      if (current !== content) {
        console.error(`out of date: specs/${rel}`);
        stale++;
      }
    } else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, content);
      console.log(`wrote specs/${rel}`);
    }
  }
  if (stale) {
    console.error('Run `npm run specs` and commit the result.');
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
