/**
 * Builds the OpenAPI and JSON Schema files in specs/ from specs/src/schemas.ts.
 *
 *   npm run specs          write the files
 *   npm run specs -- --check   exit 1 if the committed files are out of date
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { CHARGE_POINT_ID_PATTERN, MAX_MESSAGE_BYTES, SHARED_SCHEMAS, VERSIONS, ref, type Schema } from './schemas.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_VERSION = '1.0.0';
const GENERATED_NOTE = 'Generated by `npm run specs` from specs/src/schemas.ts. Do not edit by hand.';

type VersionKey = keyof typeof VERSIONS;
const versionKeys = Object.keys(VERSIONS) as VersionKey[];

const reqName = (v: VersionKey, action: string) => `${VERSIONS[v].tag}_${action}_Request`;
const resName = (v: VersionKey, action: string) => `${VERSIONS[v].tag}_${action}_Response`;

/** Every named schema: shared ones plus a request and response for each action. */
export function namedSchemas(): Record<string, Schema> {
  const out: Record<string, Schema> = { ...SHARED_SCHEMAS };
  for (const v of versionKeys) {
    const { fromCharger, fromCsms, label } = VERSIONS[v];
    for (const [action, s] of Object.entries(fromCharger)) {
      out[reqName(v, action)] = { title: `${label} ${action} request (charger → CSMS)`, ...s.request };
      out[resName(v, action)] = { title: `${label} ${action} response (CSMS → charger)`, ...s.response };
    }
    for (const [action, s] of Object.entries(fromCsms)) {
      out[reqName(v, action)] = { title: `${label} ${action} request (CSMS → charger)`, ...s.request };
      out[resName(v, action)] = { title: `${label} ${action} response (charger → CSMS)`, ...s.response };
    }
  }
  return out;
}

// ------------------------------------------------------------------ JSON Schema: inbound frames

const intEnum = (n: number): Schema => ({ type: 'integer', enum: [n] });

/** JSON Schema (2020-12) for one whole WebSocket message a charger may send to the CSMS. */
export function inboundFrameSchema(v: VersionKey): Schema {
  const { fromCharger, fromCsms, label, tag } = VERSIONS[v];
  const calls = Object.keys(fromCharger).map((action) => ({
    title: `CALL ${action}`,
    type: 'array',
    minItems: 4,
    maxItems: 4,
    prefixItems: [intEnum(2), ref('MessageId'), { type: 'string', enum: [action] }, ref(reqName(v, action))],
    items: false,
  }));
  const callResult = {
    title: 'CALLRESULT (answer to a command the CSMS sent)',
    type: 'array',
    minItems: 3,
    maxItems: 3,
    prefixItems: [intEnum(3), ref('MessageId'), { anyOf: Object.keys(fromCsms).map((a) => ref(resName(v, a))) }],
    items: false,
  };
  const callError = {
    title: 'CALLERROR',
    type: 'array',
    minItems: 5,
    maxItems: 5,
    prefixItems: [intEnum(4), ref('MessageId'), ref(`${tag}_ErrorCode`), ref('ErrorDescription'), ref('ErrorDetails')],
    items: false,
  };

  // Shared definitions plus only this version's messages.
  const defs = Object.fromEntries(
    Object.entries(namedSchemas()).filter(([name]) => name.startsWith(`${tag}_`) || !/^V(16|201)_/.test(name)),
  );
  const schema: Schema = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `https://github.com/felixreyner/ocpp-ev-charger-sim/specs/json-schema/${v}-inbound-frame.schema.json`,
    title: `${label} frame, charging station → CSMS`,
    description: [
      `Validates one complete OCPP-J WebSocket text message that a charging station sends to this CSMS over subprotocol "${v}".`,
      'Valid frames are [2, messageId, Action, payload] (CALL), [3, messageId, payload] (CALLRESULT answering a CSMS command) or [4, messageId, errorCode, description, details] (CALLERROR).',
      'Anything else (non-JSON, wrong array shape, unknown message type, unknown action, extra or mistyped fields, out-of-range values) does not validate.',
      GENERATED_NOTE,
    ].join(' '),
    oneOf: [...calls, callResult, callError],
    $defs: defs,
  };
  return JSON.parse(JSON.stringify(schema).replaceAll('#/components/schemas/', '#/$defs/'));
}

