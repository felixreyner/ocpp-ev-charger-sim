// ------------------------------------------------------------------ OpenAPI: per-action message catalogue

const exampleFor = (v: VersionKey, action: string): Record<string, unknown> | undefined => EXAMPLES[v]?.[action];

export function messagesSpec(): Schema {
  const paths: Record<string, unknown> = {};
  const tags: Array<{ name: string; description: string }> = [];
  for (const v of versionKeys) {
    const { fromCharger, fromCsms, label } = VERSIONS[v];
    const upTag = `${label}: charger → CSMS`;
    const downTag = `${label}: CSMS → charger`;
    tags.push(
      { name: upTag, description: `CALLs a charging station sends to the CSMS over subprotocol ${v}. This is the traffic to inspect in front of the CSMS.` },
      { name: downTag, description: `Commands the CSMS sends to the charging station over ${v}. The "response" is the CALLRESULT the station sends back, which also flows towards the CSMS.` },
    );
    const add = (action: string, tag: string, direction: 'charger-to-csms' | 'csms-to-charger') => {
      const example = exampleFor(v, action);
      paths[`/${v}/${action}`] = {
        post: {
          tags: [tag],
          operationId: `${VERSIONS[v].tag}_${action}`,
          summary: `${action} (${label})`,
          description: [
            'Virtual operation: OCPP is not REST. This documents the payload of one OCPP-J frame.',
            `On the wire the request is \`[2, "<messageId>", "${action}", <requestBody>]\` and the answer is \`[3, "<messageId>", <200 body>]\` or a CALLERROR \`[4, "<messageId>", "<errorCode>", "<description>", {}]\`.`,
          ].join(' '),
          'x-ocpp-action': action,
          'x-ocpp-version': v,
          'x-ocpp-direction': direction,
          requestBody: {
            required: true,
            content: { 'application/json': { schema: ref(reqName(v, action)), ...(example ? { example } : {}) } },
          },
          responses: {
            '200': { description: 'CALLRESULT payload', content: { 'application/json': { schema: ref(resName(v, action)) } } },
            default: { description: 'CALLERROR', content: { 'application/json': { schema: ref(`${VERSIONS[v].tag}_CallError`) } } },
          },
        },
      };
    };
    for (const action of Object.keys(fromCharger)) add(action, upTag, 'charger-to-csms');
    for (const action of Object.keys(fromCsms)) add(action, downTag, 'csms-to-charger');
  }

  const schemas: Record<string, Schema> = namedSchemas();
  for (const v of versionKeys) {
    const tag = VERSIONS[v].tag;
    schemas[`${tag}_CallError`] = {
      title: `${VERSIONS[v].label} CALLERROR fields`,
      description: 'Shown as an object for readability; on the wire it is [4, messageId, errorCode, errorDescription, errorDetails].',
      type: 'object',
      additionalProperties: false,
      required: ['errorCode', 'errorDescription', 'errorDetails'],
      properties: { errorCode: ref(`${tag}_ErrorCode`), errorDescription: ref('ErrorDescription'), errorDetails: ref('ErrorDetails') },
    };
  }

  return {
    openapi: '3.0.3',
    info: {
      title: 'OCPP 1.6J / 2.0.1 message catalogue for the simulator CSMS',
      version: SPEC_VERSION,
      description: [
        'Strict request and response schemas for every OCPP action this CSMS handles or sends, for schema validation and WAF tuning.',
        '',
        'OCPP-J runs over one WebSocket, not HTTP routes, so each action is described as a *virtual* `POST /{subprotocol}/{Action}` operation whose request body is the frame payload.',
        'Do not publish these paths on the CSMS. Use `ocpp-csms-gateway.openapi.yaml` for HTTP enforcement and the JSON Schemas in `specs/json-schema/` to validate whole WebSocket frames.',
        '',
        'Schemas are stricter than the minimum the CSMS checks: unknown fields are rejected, strings have length and character limits, ids and meter readings have ranges.',
        '',
        GENERATED_NOTE,
      ].join('\n'),
    },
    tags,
    paths,
    components: { schemas },
  };
}

